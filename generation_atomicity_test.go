package entdomain

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"entgo.io/ent/entc/gen"
)

// TestGenerationIsAtomicPerRun is the run-level counterpart to the per-file
// assertions in writefile_test.go, and the one that ADR-0003 exists for.
//
// The failure it pins is not a half-written file — writeFormatted never
// produced one — but a half-written RUN: two annotated entities, the second of
// which renders source goimports cannot parse. Under a loop that renamed each
// file into place as it went, entity A's files were already the new generation
// by the time B failed, leaving the consumer's tree a mix of two runs that
// `git status` presents as an inexplicable partial diff.
//
// The injection seam is the package-level template var (template_index.go);
// this test is in-package, so it can swap dtoTemplate and restore it. Nothing
// in the generator needs a hook for it.
func TestGenerationIsAtomicPerRun(t *testing.T) {
	// Valid Go for every entity but B, which gets a token no parser accepts.
	// The template still PARSES — the failure has to happen in imports.Process,
	// which is the phase-1 gate under test.
	const brokenForB = `// Code generated by entdomain extension from schema "{{ $.Name }}". DO NOT EDIT.

package ent

// {{ $.Name }}Response is a placeholder.
type {{ $.Name }}Response struct{}
{{ if eq $.Name "B" }}!!!invalid go!!!{{ end }}
`

	restore := dtoTemplate
	dtoTemplate = brokenForB
	t.Cleanup(func() { dtoTemplate = restore })

	dir := t.TempDir()

	cfg := &gen.Config{
		Target:  dir,
		Package: "example.com/app/ent",
	}
	a := newTestType("A", newStringField("name", ptr(DefaultField())))
	b := newTestType("B", newStringField("name", ptr(DefaultField())))
	a.Config, b.Config = cfg, cfg
	g := &gen.Graph{Config: cfg, Nodes: []*gen.Type{a, b}}

	// The previous generation, for BOTH entities. A's is the one a per-file
	// scheme replaces before B is ever rendered.
	previous := map[string]string{
		"a_dto.go": "package ent\n\n// A from the previous run.\ntype APrevious struct{}\n",
		"b_dto.go": "package ent\n\n// B from the previous run.\ntype BPrevious struct{}\n",
	}
	for name, content := range previous {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatalf("seeding %s: %v", name, err)
		}
	}

	ext := NewExtension(nil)
	next := gen.GenerateFunc(func(*gen.Graph) error { return nil })

	err := ext.generatePerTypeFiles(next).Generate(g)
	if err == nil {
		t.Fatal("generation succeeded on a template that emits invalid Go for entity B")
	}
	if !strings.Contains(err.Error(), "not valid Go") {
		t.Fatalf("error %q does not report a formatting failure; the run may have "+
			"aborted for an unrelated reason, which would make the assertions below vacuous", err)
	}

	for name, want := range previous {
		got, readErr := os.ReadFile(filepath.Join(dir, name))
		if readErr != nil {
			t.Fatalf("previous output %s disappeared: %v", name, readErr)
		}
		if string(got) != want {
			t.Errorf("a run that failed at entity B replaced %s.\nwant:\n%s\ngot:\n%s", name, want, got)
		}
	}

	// Nothing else may exist either: not A's filter or wiring, not the error
	// classifier, and no temporary file. A failed run touches zero paths.
	assertOnlyFiles(t, dir, "a_dto.go", "b_dto.go")
}
