package entapi

import (
	"bytes"
	"log"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// entapiHeader is a realistic generated header — the thing cleanup keys on.
const entapiHeader = `// Code generated by entapi extension from schema "Widget" (entschema/schema/widget.go). DO NOT EDIT.

package ent
`

// entHeader is ent's own generated header. Cleanup must not match it: ent's
// files sit in the same directory.
const entHeader = `// Code generated by ent, DO NOT EDIT.

package ent
`

func seed(t *testing.T, dir, name, content string) string {
	t.Helper()
	path := filepath.Join(dir, name)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("seeding %s: %v", path, err)
	}
	return path
}

func exists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

func TestRemoveStaleArtifacts_RemovesOwnedFilesNotWrittenThisRun(t *testing.T) {
	dir := t.TempDir()
	dto := seed(t, dir, "widget_dto.go", entapiHeader)
	svc := seed(t, dir, "widget_base_service.go", entapiHeader)
	handler := seed(t, dir, "widget_base_handler.go", entapiHeader)

	if err := removeStaleArtifacts(dir, map[string]bool{}); err != nil {
		t.Fatalf("removeStaleArtifacts: %v", err)
	}

	for _, path := range []string{dto, svc, handler} {
		if exists(path) {
			t.Errorf("%s survived: it carries the entapi marker and this run did not write it", path)
		}
	}
}

// TestRemoveStaleArtifacts_RemovesLegacyMarkedFiles pins ADR-0011's promise:
// files written before the entdomain→entapi rename carry the old marker, and
// cleanup owns them forever — otherwise every pre-rename consumer tree keeps
// stale files the build then trips over.
func TestRemoveStaleArtifacts_RemovesLegacyMarkedFiles(t *testing.T) {
	dir := t.TempDir()
	legacyHeader := `// Code generated by entdomain extension from schema "Widget" (entschema/schema/widget.go). DO NOT EDIT.

package ent
`
	old := seed(t, dir, "widget_dto.go", legacyHeader)
	graph := seed(t, dir, "entdomain_softdelete.go", legacyHeader)

	if err := removeStaleArtifacts(dir, map[string]bool{}); err != nil {
		t.Fatalf("removeStaleArtifacts: %v", err)
	}

	for _, path := range []string{old, graph} {
		if exists(path) {
			t.Errorf("%s survived: it carries the legacy entdomain marker and this run did not write it", path)
		}
	}
}

func TestRemoveStaleArtifacts_KeepsFilesWrittenThisRun(t *testing.T) {
	dir := t.TempDir()
	dto := seed(t, dir, "widget_dto.go", entapiHeader)

	if err := removeStaleArtifacts(dir, map[string]bool{dto: true}); err != nil {
		t.Fatalf("removeStaleArtifacts: %v", err)
	}

	if !exists(dto) {
		t.Error("cleanup deleted a file this run had just written")
	}
}

// TestRemoveStaleArtifacts_KeepsUnmarkedFiles is the criterion the whole rule
// exists for: these are files in someone's repository.
func TestRemoveStaleArtifacts_KeepsUnmarkedFiles(t *testing.T) {
	cases := map[string]string{
		"hand-written, no header at all":    "package ent\n\ntype Widget struct{}\n",
		"ent's own generated header":        entHeader,
		"marker edited into something else": "// Code generated by something else. DO NOT EDIT.\n\npackage ent\n",
		"marker below the header":           "package ent\n\n// mentions Code generated by entapi extension in prose\n",
	}

	for name, content := range cases {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			path := seed(t, dir, "widget_dto.go", content)

			if err := removeStaleArtifacts(dir, map[string]bool{}); err != nil {
				t.Fatalf("removeStaleArtifacts: %v", err)
			}

			if !exists(path) {
				t.Fatalf("cleanup deleted %s, which this extension did not write", path)
			}
		})
	}
}

// TestRemoveStaleArtifacts_IgnoresNonGoFiles pins the only thing that narrows
// the scan besides the marker. This extension writes Go source and nothing
// else, so a marked file under any other extension — documentation quoting a
// generated header, a checked-in golden copy — was not written by it.
func TestRemoveStaleArtifacts_IgnoresNonGoFiles(t *testing.T) {
	dir := t.TempDir()
	doc := seed(t, dir, "widget_dto.go.md", entapiHeader)

	if err := removeStaleArtifacts(dir, map[string]bool{}); err != nil {
		t.Fatalf("removeStaleArtifacts: %v", err)
	}

	if !exists(doc) {
		t.Errorf("cleanup deleted %s; this extension only ever writes .go files", doc)
	}
}

func TestRemoveStaleArtifacts_EmptyDirectoryIsNotAnError(t *testing.T) {
	dir := t.TempDir()
	if err := removeStaleArtifacts(dir, map[string]bool{}); err != nil {
		t.Fatalf("removeStaleArtifacts on an empty directory: %v", err)
	}
}

// TestCleanupRemovesDeletedEntityArtifacts is the deleted-entity case
// (#63, docs/adr/0004-cleanup-ownership-by-marker.md). An entity removed from
// the schema outright has no node in this run's graph, so nothing derived from
// the graph can name its files — and those files reference builders ent no
// longer generates, so leaving them breaks the consumer's build. The marker is
// what makes them identifiable without a node.
//
// The three negatives are the whole reason the scan is safe: a hand-written
// file, one of ent's own, and anything below the target directory.
func TestCleanupRemovesDeletedEntityArtifacts(t *testing.T) {
	dir := t.TempDir()

	// The entity is gone from the schema; its output still carries our marker.
	deleted := seed(t, dir, "sprocket_dto.go", entapiHeader)
	// A consumer's own file. No marker, so never a candidate.
	handWritten := seed(t, dir, "trinket_dto.go", "package ent\n\ntype Trinket struct{}\n")
	// ent's own output for the same entity. Its header is deliberately not ours.
	entOwned := seed(t, dir, "sprocket.go", entHeader)
	// ent generates one subpackage per entity, plus predicate/, migrate/, hook/…
	// The scan is top-level only, so a marked file down there is out of reach.
	sub := filepath.Join(dir, "sub")
	if err := os.MkdirAll(sub, 0o755); err != nil {
		t.Fatalf("seeding %s: %v", sub, err)
	}
	nested := seed(t, sub, "marked_dto.go", entapiHeader)

	var logs bytes.Buffer
	previous := log.Writer()
	log.SetOutput(&logs)
	defer log.SetOutput(previous)

	if err := removeStaleArtifacts(dir, map[string]bool{}); err != nil {
		t.Fatalf("removeStaleArtifacts: %v", err)
	}

	if exists(deleted) {
		t.Errorf("%s survived: the entity is gone from the schema, but the file carries the entapi marker and this run did not write it", deleted)
	}
	for _, path := range []string{handWritten, entOwned, nested} {
		if !exists(path) {
			t.Errorf("cleanup deleted %s, which this extension did not write into the directory it scans", path)
		}
	}
	if !strings.Contains(logs.String(), handWritten) {
		t.Errorf("cleanup left %s in place without saying so; from the outside that is indistinguishable from output it failed to clean up.\nlog:\n%s", handWritten, logs.String())
	}
}

// TestRemoveStaleArtifacts_GraphLevelFile covers the one file that belongs to
// no entity. The case it guards is the last schema dropping
// entapi.SoftDeleteMixin: without it the previous run's
// entapi_softdelete.go survives, publishing helpers for entities that no longer
// have a tombstone column — and it would not even compile, because the
// predicate it names is gone too.
func TestRemoveStaleArtifacts_GraphLevelFile(t *testing.T) {
	t.Run("removed when this run did not write it", func(t *testing.T) {
		dir := t.TempDir()
		path := seed(t, dir, softDeleteFileName, entapiHeader)

		// Nothing else in the directory: the graph file is not hung off any
		// entity, so its removal must not depend on one being present.
		if err := removeStaleArtifacts(dir, map[string]bool{}); err != nil {
			t.Fatalf("removeStaleArtifacts: %v", err)
		}
		if exists(path) {
			t.Errorf("%s survived: it carries the entapi marker and this run did not write it", path)
		}
	})

	t.Run("kept when this run wrote it", func(t *testing.T) {
		dir := t.TempDir()
		path := seed(t, dir, softDeleteFileName, entapiHeader)

		if err := removeStaleArtifacts(dir, map[string]bool{path: true}); err != nil {
			t.Fatalf("removeStaleArtifacts: %v", err)
		}
		if !exists(path) {
			t.Error("cleanup deleted the graph-level file this run had just written")
		}
	})

	t.Run("kept when it is not ours", func(t *testing.T) {
		dir := t.TempDir()
		path := seed(t, dir, softDeleteFileName, entHeader)

		if err := removeStaleArtifacts(dir, map[string]bool{}); err != nil {
			t.Fatalf("removeStaleArtifacts: %v", err)
		}
		if !exists(path) {
			t.Errorf("cleanup deleted %s, which does not carry the entapi marker", path)
		}
	})
}
