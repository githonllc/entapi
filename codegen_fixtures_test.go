// TestCodegenFixtures is the only test in this repository that proves the
// product of this project — generated Go source — actually builds. Every other
// test asserts on substrings of emitted code, which cannot detect that the
// result does not compile.
//
// For each fixture it runs the real ent code generator with this extension
// installed, then shells out to `go build` over the generated packages and
// fails with the compiler's own output when the build is non-zero.
//
// NOTE: this test WRITES INTO THE REPOSITORY TREE, at
// internal/fixtures/<dir>/<dir>ent/. That is deliberate: generated ent code has to
// live inside this Go module to resolve github.com/githonllc/entapi without
// a network fetch or a replace directive, and t.TempDir() is outside any
// module. The generated output is committed, so a clean checkout plus a test
// run leaves `git status` clean — a dirty tree after running this test means
// generation changed, not that the test misbehaved. Regenerate rather than
// hand-editing anything under internal/fixtures/<dir>/<dir>ent/; those files carry
// DO NOT EDIT headers.
func TestCodegenFixtures(t *testing.T) {
	root := repoRoot(t)
	goTool := goToolPath(t)

	for _, fc := range fixtures {
		t.Run(fc.dir, func(t *testing.T) {
			fixtureDir := filepath.Join(root, "internal", "fixtures", fc.dir)
			schemaDir := fixtureSchemaDir(root, fc.dir)
			targetDir := filepath.Join(fixtureDir, entDirName(fc.dir))

			if _, err := os.Stat(schemaDir); err != nil {
				t.Fatalf("fixture %q: schema directory %s: %v", fc.dir, schemaDir, err)
			}

			err := generateFixture(fc.dir, schemaDir, targetDir, fc.opts, fc.features)

			if len(fc.wantGenErr) > 0 {
				assertGenerationRefused(t, fc, targetDir, err)
				return
			}

			if err != nil {
				t.Fatalf("fixture %q: ent generation failed for schema %s: %v", fc.dir, schemaDir, err)
			}

			buildFixture(t, root, goTool, fc.dir, targetDir)
		})
	}
}

// assertGenerationRefused is the wantGenErr half of the harness: a schema the
// generator must refuse has to produce an error naming what is wrong, and has
// to leave the fixture's ent directory untouched. "It failed" is not enough —
// the message is the only thing a schema author gets, so its content is the
// assertion.
func assertGenerationRefused(t *testing.T, fc fixtureCase, targetDir string, err error) {
	t.Helper()

	if err == nil {
		t.Fatalf("fixture %q: generation succeeded, but this schema must be refused (wantGenErr %q)", fc.dir, fc.wantGenErr)
	}
	for _, want := range fc.wantGenErr {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("fixture %q: generation error does not mention %q.\ngot: %v", fc.dir, want, err)
		}
	}

	// Log it even on success: the message is what a schema author sees, and
	// `go test -v -run TestCodegenFixtures/<dir>` is how you read it back.
	t.Logf("fixture %q: generation refused, as required:\n%v", fc.dir, err)

	entries, readErr := os.ReadDir(targetDir)
	if readErr != nil {
		t.Fatalf("fixture %q: cannot read %s: %v", fc.dir, targetDir, readErr)
	}
	for _, entry := range entries {
		if entry.Name() == "schema" {
			continue
		}
		t.Errorf("fixture %q: generation was refused but wrote %s into %s; a refused generation must leave nothing behind",
			fc.dir, entry.Name(), targetDir)
	}
}

// TestCodegenFixtureStaleArtifacts is the "annotations removed between runs"
// fixture. It does not fit the table above because it needs two generation runs
// over one target directory, from two different schema packages.
//
// Run 1 uses internal/fixtures/stale/annotated/schema, where Sprocket carries
// entapi annotations. Run 2 uses .../plain/schema, identical except that
// Sprocket has none — so it no longer qualifies, and the four files run 1
// wrote for it have to go.
//
// The committed contents of internal/fixtures/stale/staleent are run 2's result, so
// a passing run leaves `git status` clean. A dirty tree afterwards means
// cleanup did not remove what it should have, or removed something it should
// not have.
func TestCodegenFixtureStaleArtifacts(t *testing.T) {
	root := repoRoot(t)
	goTool := goToolPath(t)

	fixtureDir := filepath.Join(root, "internal", "fixtures", "stale")
	targetDir := filepath.Join(fixtureDir, entDirName("stale"))
	var opts []Option

	// The last two entries are graph-level, and they are the case a name-derived
	// cleanup could never have reached: there is no entity left in the schema to
	// hang it off. An ErrorMap surviving here would be an exported symbol in the
	// consumer's package with no wiring left that uses it.
	generated := []string{
		"sprocket_dto.go", "sprocket_filter.go", "sprocket_wiring.go", "sprocket_handler.go",
		errorMapFileName, httpFileName,
	}

	// The hand-written file that must survive: it sits in the directory cleanup
	// scans, and carries ent's generic header instead of entapi's marker.
	handWritten := filepath.Join(targetDir, "trinket_dto.go")
	before, err := os.ReadFile(handWritten)
	if err != nil {
		t.Fatalf("reading the hand-written fixture file %s: %v", handWritten, err)
	}

	// Run 1: Sprocket is annotated.
	mustGenerateFixture(t, "stale", filepath.Join(fixtureDir, "annotated", "schema"), targetDir, opts, nil)
	for _, name := range generated {
		path := filepath.Join(targetDir, name)
		content, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("run 1 did not generate %s: %v", path, err)
		}
		if !strings.Contains(string(content), entapiHeaderMarker) {
			t.Fatalf("run 1 output %s does not carry the entapi marker %q, "+
				"which is what cleanup identifies its own files by", path, entapiHeaderMarker)
		}
	}

	// Run 2: the same entity without annotations.
	mustGenerateFixture(t, "stale", filepath.Join(fixtureDir, "plain", "schema"), targetDir, opts, nil)
	for _, name := range generated {
		path := filepath.Join(targetDir, name)
		if _, err := os.Stat(path); !os.IsNotExist(err) {
			t.Errorf("%s still exists after Sprocket lost its annotations; "+
				"it compiles against a schema that no longer describes it", path)
		}
	}

	after, err := os.ReadFile(handWritten)
	if err != nil {
		t.Fatalf("cleanup deleted the hand-written file %s: %v", handWritten, err)
	}
	if string(after) != string(before) {
		t.Errorf("cleanup modified the hand-written file %s", handWritten)
	}

	buildFixture(t, root, goTool, "stale", targetDir)
}

// generateFixture runs ent generation with this extension over schemaDir,
// writing into targetDir. The error is returned rather than fatal: a fixture
// with wantGenErr needs it as its assertion, not as a failure.
func generateFixture(name, schemaDir, targetDir string, opts []Option, features []gen.Feature) error {
	pkgPath := fixtureEntPkgPath(name)
	return entc.Generate(schemaDir, &gen.Config{
		Target:   targetDir,
		Package:  pkgPath,
		Features: features,
	}, entc.Extensions(NewExtensionWithOptions(opts...)))
}

// mustGenerateFixture is generateFixture for the callers that have no reason to
// tolerate a failure.
func mustGenerateFixture(t *testing.T, name, schemaDir, targetDir string, opts []Option, features []gen.Feature) {
	t.Helper()
	if err := generateFixture(name, schemaDir, targetDir, opts, features); err != nil {
		t.Fatalf("fixture %q: ent generation failed for schema %s: %v", name, schemaDir, err)
	}
}

// buildFixture compiles everything under the fixture directory and fails with
// the compiler's own output.
func buildFixture(t *testing.T, root, goTool, name, targetDir string) {
	t.Helper()
	pattern := "./internal/fixtures/" + name + "/..."
	cmd := exec.Command(goTool, "build", pattern)
	cmd.Dir = root
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("fixture %q: generated output does not compile.\n"+
			"    generated into: %s\n"+
			"    command:        %s build %s (in %s)\n"+
			"    error:          %v\n"+
			"    compiler output:\n%s",
			name, targetDir, goTool, pattern, root, err, out)
	}
}

// repoRoot returns the directory holding this test file. Paths are derived from
// the test's own location rather than the process working directory so the
// harness does not depend on where `go test` was invoked from.
func repoRoot(t *testing.T) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("cannot determine the location of this test file")
	}
	return filepath.Dir(file)
}

// goToolPath locates the go command used to compile the generated output.
func goToolPath(t *testing.T) string {
	t.Helper()
	if path, err := exec.LookPath("go"); err == nil {
		return path
	}
	path := filepath.Join(runtime.GOROOT(), "bin", "go")
	if _, err := os.Stat(path); err != nil {
		t.Fatalf("cannot locate the go tool: not on PATH and not at %s", path)
	}
	return path
}
