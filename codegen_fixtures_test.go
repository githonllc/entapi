// entapiHeaderMarker is spelled out here rather than taken from the
// implementation's constant on purpose: the marker is what tells this
// extension's files apart from a consumer's, so a test that reused the constant
// would follow it wherever it was changed to.
const entapiHeaderMarker = "Code generated by entapi extension"

// modulePath is this module's import path, from go.mod. Generated fixture
// packages live underneath it, which is what lets the generated code import
// entapi itself without a replace directive.
const modulePath = "github.com/githonllc/entapi"

// entDirName is the directory a fixture's generated ent package lives in,
// relative to internal/fixtures/<dir>.
//
// It is <dir>ent rather than plain ent, and that is the whole of the fix for
// #49: a Go package is named after the last element of its import path, so
// this is what makes internal/fixtures/basic/basicent declare `package
// basicent` instead of a tenth `package ent`. goimports resolves a bare `ent.`
// reference by package name against every candidate in the module and picks
// from its cache, so identical names across fixtures made generated imports
// non-deterministic. TestNoAmbiguousEntPackages is the standing guard.
//
// Every fixture goes through here, including the wantGenErr ones that generate
// nothing. They own no ent package to collide with, but the harness derives one
// path from one name, and carving out an exception would put the exception in
// the harness rather than in the three directories it applies to.
func entDirName(fixtureDir string) string { return fixtureDir + "ent" }

// fixtureEntPkgPath is the import path generation writes to, and the single
// place tests should get it from rather than concatenating it by hand.
func fixtureEntPkgPath(fixtureDir string) string {
	return modulePath + "/internal/fixtures/" + fixtureDir + "/" + entDirName(fixtureDir)
}

// fixtureSchemaDir is the on-disk hand-written schema package for a fixture.
// Paired with fixtureEntPkgPath so the two never drift apart: every test that
// loads a fixture graph needs both, and a mismatch between them makes ent
// generate against the wrong package path without complaining.
func fixtureSchemaDir(root, fixtureDir string) string {
	return filepath.Join(root, "internal", "fixtures", fixtureDir, entDirName(fixtureDir), "schema")
}

// fixtureCase is one fixture directory under internal/fixtures.
//
// Adding coverage is one new directory
// (internal/fixtures/<dir>/<dir>ent/schema, holding a hand-written ent schema)
// plus one line in the fixtures table below. Nothing else in the harness needs
// to change.
type fixtureCase struct {
	// dir is the directory name under internal/fixtures.
	dir string
	// opts are the extension options generation runs with.
	opts []Option
	// features are ent codegen features this fixture specifically exercises.
	features []gen.Feature
	// wantGenErr, when non-empty, turns the case around: generation is
	// required to FAIL, and its error must contain every listed substring.
	// Nothing is compiled, and nothing may be written under <dir>/<dir>ent besides
	// the hand-written schema package — a refused generation that still leaves
	// files behind is a bug of its own.
	//
	// This is how a schema the generator must refuse gets covered. Adding one
	// is still a directory plus a line in the table.
	wantGenErr []string
}

